# pull_2025.py
# Export the 2025 anonymous `submissions` collection and bake aggregate pick
# counts into a static file so the 2025 page no longer needs Firestore.
#
# Outputs:
#   2025_submissions.json   - raw dump (gitignored: names may be emails)
#   2025/js/stats-data.js   - aggregate counts only, served by the site

from google.cloud import firestore
from google.oauth2 import service_account
from pathlib import Path
import json

PROJECT_ID = "hwp53man-7e6ab"
SERVICE_ACCOUNT_PATH = Path("serviceAccount.json")


def main():
    creds = service_account.Credentials.from_service_account_file(str(SERVICE_ACCOUNT_PATH))
    client = firestore.Client(project=PROJECT_ID, credentials=creds)

    raw = []
    for doc in client.collection("submissions").stream():
        d = doc.to_dict() or {}
        date = d.get("date")
        raw.append({
            "id": doc.id,
            "name": d.get("name"),
            "date": date.isoformat() if date else None,
            "roster": d.get("roster") or [],
            "squad": d.get("squad") or [],
        })
    raw.sort(key=lambda r: r["date"] or "")

    roster, squad = {}, {}
    for r in raw:
        for n in r["roster"]:
            roster[n] = roster.get(n, 0) + 1
        for n in r["squad"]:
            squad[n] = squad.get(n, 0) + 1

    Path("2025_submissions.json").write_text(json.dumps(raw, indent=2), encoding="utf-8")
    stats = {"total": len(raw), "roster": roster, "squad": squad}
    Path("2025/js/stats-data.js").write_text(
        "// Generated by pull_2025.py. Aggregate 2025 pick counts (frozen).\n"
        f"window.HWP_2025_STATS = {json.dumps(stats, indent=2, ensure_ascii=False)};\n",
        encoding="utf-8")
    print(f"{len(raw)} submissions. Wrote 2025_submissions.json, 2025/js/stats-data.js")


if __name__ == "__main__":
    main()
